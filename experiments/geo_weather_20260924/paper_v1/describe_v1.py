"""Descriptive statistics of Section 2 on the development tranche (observed outcomes only, no model).

  panel size        county-events, counties, states, systems per regime
  renewed growth    the outage fraction rises by at least 2 points within 2 hours somewhere in hours 72-215
                    (both hours observed), overall and by regime
  initiation        county-events with no customer out at hour 71 that later reach at least 2%
Prints the numbers and writes paper_v1/generated/numbers_data.tex."""
from __future__ import annotations

import collections
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
FEAT = ROOT / "data" / "interim" / "panel_v1" / "features_v1D.npz"
RWORD = {"tropical": "Tropical", "winter": "Winter", "synoptic_wind": "Synoptic", "convective": "Convective",
         "heavy_rain": "Rain"}


def main() -> None:
    z = np.load(FEAT)
    fips, sysv, reg = z["fips"].astype(str), z["system"].astype(str), z["regime"].astype(str)
    y = np.where(z["obs_full"], z["y_full"], np.nan).astype(float)
    n = len(fips)
    rise = y[:, 74:216] - y[:, 72:214]                    # y_t - y_{t-2}, t = 74..215 (both inside the window)
    rise = np.concatenate([y[:, 72:74] - y[:, 70:72], rise], 1)   # t = 72, 73 against the prefix
    renewed = np.nanmax(np.where(np.isnan(rise), -1.0, rise), 1) >= 0.02
    y71 = z["y0"].astype(float)
    peak = np.nanmax(np.where(np.isnan(y[:, 72:216]), -1.0, y[:, 72:216]), 1)
    served = y71 == 0
    systems = dict(zip(sysv, reg))
    out = dict(NEvents=n, NCounties=len(set(fips)), NStates=len({f[:2] for f in fips}), NSystems=len(systems),
               NRenewed=int(renewed.sum()), ShareRenewed=renewed.mean(), NServedAtOrigin=int(served.sum()),
               NInitiated=int((served & (peak >= 0.02)).sum()))
    for r, w in RWORD.items():
        out[f"ShareRenewed{w}"] = renewed[reg == r].mean()
    print(out, collections.Counter(systems.values()))
    fmt = lambda v: f"{100 * v:.0f}\\%" if isinstance(v, float) else f"{v:,}".replace(",", "{,}")  # noqa: E731
    (HERE / "generated").mkdir(exist_ok=True)
    (HERE / "generated" / "numbers_data.tex").write_text(
        "% generated by paper_v1/describe_v1.py; do not edit\n"
        + "\n".join(rf"\newcommand{{\{k}}}{{{fmt(v)}}}" for k, v in out.items()) + "\n")


if __name__ == "__main__":
    main()
